# '구조조정'이 사람 자르는 얘기가 아니라 부실기업 정리·금융 얘기일 때 (−8)
FALSE_FRIEND = re.compile(r"구조조정기업|구조조정 펀드|구조조정 평가|기업 구조조정|부실기업|기업가치|재도약 지원|기보|유암코|캠코|채권단|산업은행|교육청")

# 통계 수치가 들어간 제목은 신뢰도가 높다 → 보너스
NUMBER_PATTERN = re.compile(r"\d+[\.,]?\d*\s*(%|명|만|억|조|건|개|위|배|포인트)")

MIN_SCORE = 12
MAX_HITS = 3               # 같은 섹션 키워드는 제목·요약 각각 3개까지만 센다 (키워드 중첩 과점수 방지)
TITLE_WEIGHT = 2
BODY_WEIGHT = 1
DEMOTE_PENALTY = 8
NUMBER_BONUS = 3
SEASON_MONTHS = {3, 4, 9, 10}     # 상·하반기 공채 시즌
SEASON_BONUS = 4                  # 시즌에 채용 섹션 기사 가산


def is_season(today=None):
    return (today or _date.today()).month in SEASON_MONTHS


def slots(today=None):
    """섹션별 지면 수. 시즌이면 채용 7건·지표 2건, 평시 5·5·4·3·3."""
    season = is_season(today)
    return {s["key"]: (s["season_slots"] if season else s["slots"]) for s in SECTIONS}


def _count(text, keywords):
    """텍스트에 등장한 키워드 목록"""
    return [kw for kw in keywords if kw.lower() in text]


def classify_detail(title, body="", source_bonus=0, today=None):
    """
    (섹션key, 점수, 매칭키워드, 가감 내역dict) — 가감 내역은 디버깅·시뮬레이션용.
    """
    t = title.lower()
    b = (body or "").lower()[:600]   # 요약문은 앞부분만 (RSS 설명문 꼬리 노이즈 차단)

    for kw in EXCLUDE:
        if kw in title:
            return None, 0, [], {"배제": kw}

    # core 키워드가 있는 섹션 중에서만 고른다 (회사 이름·'채용' 같은 sub만으로는 못 올라온다)
    best = (None, 0, [])
    for sec in SECTIONS:
        core_t = _count(t, sec["core"])[:MAX_HITS]
        core_b = _count(b, sec["core"])[:MAX_HITS]
        if not core_t and not core_b:
            continue
        sub_t = _count(t, sec["sub"])[:MAX_HITS]
        sub_b = _count(b, sec["sub"])[:MAX_HITS]
        score = (3 * TITLE_WEIGHT * len(core_t) + 3 * BODY_WEIGHT * len(core_b)
                 + 1 * TITLE_WEIGHT * len(sub_t) + 1 * BODY_WEIGHT * len(sub_b))
        if score > best[1]:
            best = (sec["key"], score, list(dict.fromkeys(core_t + sub_t))[:4])

    key, score, matched = best
    adj = {}
    # 커리어의 변화 필수 규칙: "40대 희망퇴직", "중장년 AI에 밀려" 같은 기사는 섹션 5로
    if AGE_RE.search(title) and SHIFT_RE.search(title):
        key = "future"
        adj["커리어변화"] = 6
    if not key:
        return None, score, matched, {"core없음": True}

    if NUMBER_PATTERN.search(title):
        adj["숫자"] = NUMBER_BONUS
    if _count(t, [k.lower() for k in JOB_BONUS]):
        adj["직무"] = 4
    if _count(title, FIRM_BONUS):
        adj["회사유형"] = 3
    if _count(title, READER_BONUS):
        adj["독자"] = 3
    if key == "hiring" and is_season(today):
        adj["시즌"] = SEASON_BONUS
    if _count(title, OFF_TARGET):
        adj["비타깃"] = -6
    if LOCAL_PR.search(title) and not LOCAL_EXEMPT.search(title):
        adj["지자체"] = -8
    if FOREIGN_STAT.search(title):
        adj["해외지표"] = -6
    if PR_TRAINING.search(title) and TRAINING_HOST.search(title):
        adj["양성홍보"] = -8
    if FALSE_FRIEND.search(title):
        adj["금융구조조정"] = -8
    demoted = sum(1 for kw in DEMOTE if kw in title)
    if demoted:
        adj["행사홍보"] = -DEMOTE_PENALTY * demoted
    adj["언론사"] = source_bonus

    score += sum(adj.values())
    if score < MIN_SCORE:
        return None, score, matched, adj
    return key, score, matched, adj


def classify(title, body="", source_bonus=0):
    """기사 제목/요약을 보고 (섹션key, 점수, 매칭키워드) 를 판정한다. 탈락이면 section=None."""
    key, score, matched, _ = classify_detail(title, body, source_bonus)
    return key, score, matched


def section_by_key(key):
    for s in SECTIONS:
        if s["key"] == key:
            return s
    return None
